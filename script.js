const imageLightbox=document.querySelector('#imageLightbox');
const imageLightboxImage=document.querySelector('#imageLightboxImage');
const imageLightboxCaption=document.querySelector('#imageLightboxCaption');
const imageLightboxClose=document.querySelector('.image-lightbox-close');
let lightboxPreviousOverflow='';
function closeImageLightbox(){
  if(!imageLightbox||!imageLightbox.classList.contains('is-open'))return;
  imageLightbox.classList.remove('is-open');
  imageLightbox.setAttribute('aria-hidden','true');
  imageLightboxImage.removeAttribute('src');
  imageLightboxImage.alt='';
  imageLightboxCaption.textContent='';
  document.body.style.overflow=lightboxPreviousOverflow;
  document.documentElement.classList.remove('image-lightbox-open');
}
function openImageLightbox(image){
  if(!imageLightbox||!imageLightboxImage)return;
  lightboxPreviousOverflow=document.body.style.overflow;
  imageLightboxImage.src=image.currentSrc||image.src;
  imageLightboxImage.alt=image.alt||'';
  imageLightboxCaption.textContent=image.alt||'';
  imageLightbox.classList.add('is-open');
  imageLightbox.setAttribute('aria-hidden','false');
  document.documentElement.classList.add('image-lightbox-open');
  document.body.style.overflow='hidden';
  imageLightboxClose?.focus();
}
